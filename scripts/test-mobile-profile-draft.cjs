const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const file = path.resolve(__dirname, '../apps/mobile/src/features/profile/utils/profile-draft.ts');
const compiled = new Module(file);
compiled._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const { ProfileDraft } = compiled.exports;
const draft = new ProfileDraft();
const initial = { name: 'Alice', phone: '0600000000', photo: 'old.jpg', address: { lat: 48, lng: 2, label: 'Adresse fictive' }, qualifications: ['IDE'], biography: 'Présentation' };
let checks = 0;
const equal = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
equal(draft.merge('patient-a', initial, {}), initial);
const edited = { ...initial, name: 'Alicia', phone: '', biography: '', qualifications: ['IDE','AUTRE'] };
const newPhoto = { ...initial, photo: 'new.jpg' };
const merged = draft.merge('patient-a', newPhoto, edited);
equal(merged.name, 'Alicia');
equal(merged.phone, '');
equal(merged.biography, '');
equal(merged.qualifications, ['IDE','AUTRE']);
equal(merged.photo, 'new.jpg');
equal(merged.address, initial.address);
const refreshed = draft.merge('patient-a', { ...newPhoto, name: 'Nom externe' }, merged);
equal(refreshed.name, 'Alicia');
const saved = { ...refreshed };
equal(draft.merge('patient-a', saved, refreshed), saved);
equal(draft.merge('patient-a', { ...saved, name: 'Mise à jour distante' }, saved).name, 'Mise à jour distante');
const second = { ...initial, name: 'Béatrice', address: null };
equal(draft.merge('patient-b', second, edited), second);
const addressDraft = new ProfileDraft();
addressDraft.merge('patient', initial, {});
const reordered = { ...initial, address: { label: 'Adresse fictive', lng: 2, lat: 48 } };
const remoteAddress = { ...initial, address: { label: 'Nouvelle adresse', lng: 3, lat: 49 } };
equal(addressDraft.merge('patient', remoteAddress, reordered).address, remoteAddress.address);
equal(addressDraft.merge('patient', remoteAddress, { ...remoteAddress, address: null }).address, null);
console.log(`${checks} assertions passed: edits survive photo/visibility refreshes, untouched fields update, saved values become the baseline and accounts remain isolated.`);
