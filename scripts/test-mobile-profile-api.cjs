const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const file = path.resolve(__dirname, '../apps/mobile/src/features/profile/api/profile.service.ts');
let response = { success: false, error: 'Refus synthétique' };
const requests = [];
const api = Object.fromEntries(['get', 'post', 'put'].map(method => [method, async (url, body) => {
  requests.push({ method, url, body });
  return response;
}]));
const compiled = new Module(file);
compiled.require = name => name === '@/api/client' ? { api } : require(name);
compiled._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const service = compiled.exports;
let checks = 0;
const equal = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const rejects = async (promise, match) => { await assert.rejects(promise, match); checks++; };
(async () => {
  await rejects(service.fetchUser('fixture/id'), /Refus/);
  await rejects(service.updateProfileImages('fixture/id', { profile_image_url: null }), /Refus/);
  await rejects(service.fetchNurseCategoryPreferences(), /Refus/);
  await rejects(service.updateNurseCategoryPreference('care-fixture', false), /Refus/);
  response = { success: true, data: { id: 'other-user' } };
  await rejects(service.fetchUser('fixture/id'), /Profil indisponible/);
  response = { success: true, data: null };
  await rejects(service.fetchUser('fixture/id'), /Profil indisponible/);
  await rejects(service.fetchNurseCategoryPreferences(), /indisponibles/);
  response = { success: true, data: { id: 'fixture/id', is_public_profile_enabled: '0', is_accepting_appointments: '1', accept_rdv_saturday: 0, accept_rdv_sunday: 1, prescription_generation_enabled: null } };
  const result = await service.fetchUser('fixture/id', 'full');
  equal(requests.at(-1).url, '/users/fixture%2Fid');
  equal(result.data.is_public_profile_enabled, false);
  equal(result.data.is_accepting_appointments, true);
  equal(result.data.accept_rdv_saturday, false);
  equal(result.data.accept_rdv_sunday, true);
  equal(result.data.prescription_generation_enabled, null);
  await service.fetchUser('fixture/id');
  equal(requests.at(-1).url, '/users/fixture%2Fid?scope=mobile');
  response = { success: true, data: [{ category_id: 'care-a', is_enabled: '0' }, { category_id: 'care-b', is_enabled: '1' }] };
  equal((await service.fetchNurseCategoryPreferences()).data.map(row => row.is_enabled), [false, true]);
  response = { success: true };
  equal((await service.updateProfileImages('fixture/id', { profile_image_url: null })).success, true);
  equal(requests.at(-1).body, { profile_image_url: null });
  equal(requests.at(-1).url, '/users/fixture%2Fid');
  equal((await service.updateNurseCategoryPreference('care-fixture', false)).success, true);
  equal(requests.at(-1).body, { category_id: 'care-fixture', is_enabled: false });
  console.log(`${checks} assertions passed: profile identity, failed reads and writes, image removal, encoded identifiers and legacy boolean flags.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
