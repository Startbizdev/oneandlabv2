const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const file = path.resolve(__dirname, '../frontend/utils/appointmentEditData.ts');
const compiled = new Module(file);
compiled._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const { appointmentEditAddress: address, appointmentRecord: record, appointmentAvailability: availability, appointmentCareOptions: options } = compiled.exports;
const expected = { label: '10 rue Exemple', lat: 48.86, lng: 2.34 };
assert.deepEqual(address({ address: expected }), expected);
assert.deepEqual(address({ address: expected.label, form_data: { address: expected } }), expected);
assert.deepEqual(address({ address: expected.label, location_lat: '48.86', location_lng: '2.34' }), expected);
assert.deepEqual(address({ form_data: JSON.stringify({ address: JSON.stringify(expected) }) }), expected);
assert.deepEqual(address({ address: JSON.stringify(expected) }), expected);
assert.equal(address({ address: expected.label }).label, expected.label);
assert.ok(Number.isNaN(address({ address: expected.label }).lat));
assert.equal(address({}), null);
assert.deepEqual(record('not JSON'), {});
assert.deepEqual(record('[]'), {});
assert.equal(availability({ type: 'custom', range: [8, 10] }), '{"type":"custom","range":[8,10]}');
assert.equal(availability('{"type":"all_day"}'), '{"type":"all_day"}');
assert.deepEqual(options('{"dose":2,"detail":"Texte conservé","unexpected":{}}'), { dose: 2, detail: 'Texte conservé' });
console.log('13 assertions passed: legacy appointment address, availability and care options.');
