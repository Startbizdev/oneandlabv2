const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const file = path.resolve(__dirname, '../packages/shared-utils/src/resumable-appointment-batch.ts');
const compiled = new Module(file);
compiled._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { ResumableAppointmentBatch } = compiled.exports;
(async () => {
  const batch = new ResumableAppointmentBatch();
  const calls = [], artifacts = [];
  let fail = true;
  const create = async p => { calls.push(p); if (p === 'second' && fail) throw new Error('Service unavailable'); return p + '-id'; };
  const attach = async (_, id) => { artifacts.push(id); };
  const partial = await batch.run('same', ['first', 'second'], create, attach);
  assert.equal(partial.success, false);
  assert.deepEqual(partial.createdIds, ['first-id']);
  assert.deepEqual(artifacts, ['first-id']);
  const changed = await batch.run('changed', ['other'], create, attach);
  assert.equal(changed.success, false);
  assert.deepEqual(calls, ['first', 'second']);
  fail = false;
  const retry = await batch.run('same', ['first', 'second'], create, attach);
  assert.equal(retry.success, true);
  assert.deepEqual(retry.createdIds, ['first-id', 'second-id']);
  assert.deepEqual(calls, ['first', 'second', 'second']);
  assert.deepEqual(artifacts, ['first-id', 'second-id']);
  const next = await batch.run('new', ['third'], create, attach);
  assert.equal(next.success, true);
  assert.deepEqual(next.createdIds, ['third-id']);
  const artifactBatch = new ResumableAppointmentBatch();
  let created = 0, copied = 0, uploaded = 0;
  let failUpload = true;
  const attachWithRetry = async (_, id) => {
    await artifactBatch.completeOnce(id + ':copy', async () => { copied++; });
    await artifactBatch.completeOnce(id + ':upload', async () => { uploaded++; if (failUpload) throw new Error('Upload failed'); });
  };
  const createOnce = async () => { created++; return 'with-documents'; };
  assert.equal((await artifactBatch.run('documents', ['care'], createOnce, attachWithRetry)).success, false);
  failUpload = false;
  assert.equal((await artifactBatch.run('documents', ['care'], createOnce, attachWithRetry)).success, true);
  assert.equal(created, 1);
  assert.equal(copied, 1);
  assert.equal(uploaded, 2);
  const lostResponse = new ResumableAppointmentBatch();
  const requestIds = [];
  const persisted = new Map();
  let lose = true;
  const server = async (payload, key) => {
    requestIds.push(key);
    if (!persisted.has(key)) persisted.set(key, `server-${persisted.size}`);
    if (lose) { lose = false; throw new Error('Response lost after commit'); }
    return persisted.get(key);
  };
  assert.equal((await lostResponse.run('same request', ['care'], server, async()=>{})).success, false);
  assert.equal((await lostResponse.run('same request', ['care'], server, async()=>{})).success, true);
  assert.equal(requestIds[0], requestIds[1]);
  assert.equal(persisted.size, 1);
  await lostResponse.run('new request', ['care'], server, async()=>{});
  assert.notEqual(requestIds[1], requestIds[2]);
  console.log('21 resumable booking assertions passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
