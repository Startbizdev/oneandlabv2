const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const ts = require('typescript');
const { effectScope } = require('vue');
const pending = [];
const file = path.resolve(__dirname, '../frontend/composables/useAdminDispatch.ts');
const compiled = new Module(file);
compiled.require = name => name === '~/utils/api' ? { apiFetch: url => new Promise((resolve, reject) => pending.push({ url, resolve, reject })) } : require(name);
compiled._compile('const {ref,onScopeDispose}=require("vue");\n' + ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const { useAdminDispatch } = compiled.exports;
const ok = data => ({ success: true, data });
(async () => {
  const scope = effectScope();
  const state = scope.run(() => useAdminDispatch());
  const old = state.fetchDashboard({ search: 'old' });
  const current = state.fetchDashboard({ search: 'current' });
  pending[1].resolve(ok({ rows: [{ id: 'current' }] }));
  await current;
  pending[0].resolve(ok({ rows: [{ id: 'old' }] }));
  await old;
  assert.equal(state.dashboardData.value.rows[0].id, 'current');
  assert.equal(state.loading.value, false);
  const broken = state.fetchDashboard({ search: 'broken' });
  assert.equal(state.dashboardData.value, null);
  pending[2].resolve({ success: false });
  await broken;
  assert.ok(state.error.value);
  const firstDetail = state.fetchDetail('old');
  state.clearDetail();
  const lastDetail = state.fetchDetail('current');
  pending[4].resolve(ok({ identity: { appointment_id: 'current' } }));
  await lastDetail;
  pending[3].reject(new Error('late failure'));
  await firstDetail;
  assert.equal(state.detailData.value.identity.appointment_id, 'current');
  assert.equal(state.detailError.value, null);
  assert.equal(state.detailLoading.value, false);
  const closing = state.fetchDetail('closing');
  state.clearDetail();
  pending[5].resolve(ok({ identity: { appointment_id: 'closing' } }));
  await closing;
  assert.equal(state.detailData.value, null);
  const disposed = state.fetchDashboard();
  scope.stop();
  pending[6].resolve(ok({ rows: [{ id: 'disposed' }] }));
  await disposed;
  assert.equal(state.dashboardData.value, null);
  const secondScope = effectScope();
  assert.equal(secondScope.run(() => useAdminDispatch()).dashboardData.value, null);
  secondScope.stop();
  console.log('10 assertions passed: stale searches, unavailable data, closed/reopened details and disposal isolation.');
})().catch(error => { console.error(error); process.exitCode = 1; });
